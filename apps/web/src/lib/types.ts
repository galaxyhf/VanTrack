export type Eta = {
  available: boolean;
  reason?: string;
  arrival?: string;
  minutes?: number;
  distance?: number;
  delayMinutes?: number;
  stale?: boolean;
  source?: string;
  updatedAt?: string;
  isSimulated?: boolean;
};
export type Notification = {
  id: string;
  type: string;
  title: string;
  content: string;
  isRead: boolean;
  tripId: string | null;
  createdAt: string;
};
export type Message = {
  id: string;
  senderId: string;
  senderName: string;
  content: string;
  operational: boolean;
  createdAt: string;
};
export type List<T> = { data: T[]; page?: number; limit?: number };
